"""Build the crawlable HTML directory for the site's three content pillars."""
from __future__ import annotations

import argparse
import html
import json
import os
import tempfile
from dataclasses import dataclass
from pathlib import Path, PurePosixPath
from urllib.parse import urlsplit


ROOT = Path(__file__).resolve().parents[1]
BASE_URL = "https://jaketroubleshoots.com"
PAGE_SIZE = 100
MASTER_PATH = "content-directory.html"
DIRECTORY_NAME = "directory"
GENERATED_MARKER = "<!-- Generated by tools/build_content_directory.py. Do not edit. -->"


def _filesystem_path(path: Path) -> Path:
    """Return a Windows extended-length path when the checkout path requires it."""
    resolved = path.resolve()
    value = str(resolved)
    if os.name == "nt" and not value.startswith("\\\\?\\"):
        return Path("\\\\?\\" + value)
    return resolved


class DirectoryBuildError(ValueError):
    """Raised when source records cannot produce a safe public directory."""


@dataclass(frozen=True)
class Pillar:
    key: str
    name: str
    singular_name: str
    source_path: str
    url_prefix: str
    page_prefix: str


PILLARS = (
    Pillar(
        key="troubleshooting-guides",
        name="Troubleshooting Guides",
        singular_name="troubleshooting guide",
        source_path="data/guides.json",
        url_prefix="guides/",
        page_prefix="troubleshooting-guides",
    ),
    Pillar(
        key="preventive-maintenance",
        name="Preventive Maintenance Procedures",
        singular_name="preventive maintenance procedure",
        source_path="data/preventive-maintenance.json",
        url_prefix="preventive-maintenance/",
        page_prefix="preventive-maintenance",
    ),
    Pillar(
        key="biomed-basics",
        name="Biomed Basics Articles",
        singular_name="Biomed Basics article",
        source_path="data/biomed-basics.json",
        url_prefix="biomed-basics/",
        page_prefix="biomed-basics",
    ),
)


def _read_json(path: Path) -> object:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError as error:
        raise DirectoryBuildError(f"Required catalog does not exist: {path}") from error
    except json.JSONDecodeError as error:
        raise DirectoryBuildError(f"Invalid JSON in {path}: {error}") from error


def _records_for_pillar(root: Path, pillar: Pillar) -> list[dict[str, object]]:
    source = root / pillar.source_path
    data = _read_json(source)
    if not isinstance(data, list):
        raise DirectoryBuildError(f"Catalog must contain a JSON list: {source}")

    if pillar.key != "troubleshooting-guides":
        if not all(isinstance(record, dict) for record in data):
            raise DirectoryBuildError(f"Catalog contains a non-object record: {source}")
        return data

    records: list[dict[str, object]] = []
    for item in data:
        if isinstance(item, dict):
            records.append(item)
            continue
        if not isinstance(item, str) or not item.strip():
            raise DirectoryBuildError(f"Guide manifest contains an invalid shard entry: {item!r}")
        shard_relative = PurePosixPath(item)
        if shard_relative.is_absolute() or ".." in shard_relative.parts:
            raise DirectoryBuildError(f"Unsafe guide shard path: {item}")
        shard = root.joinpath(*shard_relative.parts)
        shard_data = _read_json(shard)
        if not isinstance(shard_data, list) or not all(isinstance(record, dict) for record in shard_data):
            raise DirectoryBuildError(f"Guide shard must contain a list of objects: {shard}")
        records.extend(shard_data)
    return records


def _validated_entries(root: Path, pillar: Pillar) -> list[tuple[str, str]]:
    entries: list[tuple[str, str]] = []
    for number, record in enumerate(_records_for_pillar(root, pillar), start=1):
        title = record.get("title")
        url = record.get("url")
        if not isinstance(title, str) or not title.strip():
            raise DirectoryBuildError(f"{pillar.source_path} record {number} has no valid title")
        if not isinstance(url, str) or not url.strip():
            raise DirectoryBuildError(f"{pillar.source_path} record {number} has no valid URL")
        title = " ".join(title.split())
        url = url.strip()
        parsed = urlsplit(url)
        relative = PurePosixPath(parsed.path)
        if (
            parsed.scheme
            or parsed.netloc
            or parsed.query
            or parsed.fragment
            or "\\" in url
            or relative.is_absolute()
            or ".." in relative.parts
            or not url.startswith(pillar.url_prefix)
            or relative.suffix.lower() != ".html"
            or relative.as_posix() != url
        ):
            raise DirectoryBuildError(f"Unsafe or unexpected {pillar.name} URL: {url}")
        target = root.joinpath(*relative.parts)
        if not _filesystem_path(target).is_file():
            raise DirectoryBuildError(f"Published destination does not exist for {url}: {target}")
        entries.append((title, url))
    return sorted(entries, key=lambda entry: (entry[0].casefold(), entry[1]))


def load_content(root: Path = ROOT) -> dict[Pillar, list[tuple[str, str]]]:
    """Load, validate, and deduplicate the authoritative published records."""
    content: dict[Pillar, list[tuple[str, str]]] = {}
    seen: dict[str, str] = {}
    for pillar in PILLARS:
        entries = _validated_entries(root, pillar)
        for title, url in entries:
            if url in seen:
                raise DirectoryBuildError(
                    f"Duplicate published URL {url!r} in {pillar.name}; already used by {seen[url]!r}"
                )
            seen[url] = title
        content[pillar] = entries
    return content


def _page_path(pillar: Pillar, page_number: int) -> str:
    return f"{DIRECTORY_NAME}/{pillar.page_prefix}-{page_number:03d}.html"


