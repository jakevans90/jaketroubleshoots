def _master_page(content: dict[Pillar, list[tuple[str, str]]], page_size: int) -> str:
    sections = []
    total = sum(len(entries) for entries in content.values())
    for pillar, entries in content.items():
        page_count = (len(entries) + page_size - 1) // page_size
        links = []
        for index in range(page_count):
            start = index * page_size + 1
            end = min((index + 1) * page_size, len(entries))
            links.append(
                f'        <li><a href="{_page_path(pillar, index + 1)}">'
                f'{html.escape(pillar.name)} {start}&ndash;{end}</a></li>'
            )
        sections.append(
            f'''    <section class="content-box" id="{pillar.key}">
      <h2>{html.escape(pillar.name)}</h2>
      <p>{len(entries):,} published {html.escape(pillar.name.lower())}.</p>
      <ul>
{chr(10).join(links)}
      </ul>
    </section>'''
        )
    main = f'''<section class="hero">
  <h1 id="page-heading" tabindex="-1">Content Directory</h1>
  <p>Static, crawlable links to all {total:,} published troubleshooting guides, preventive maintenance procedures, and Biomed Basics articles.</p>
</section>
<main>
{chr(10).join(sections)}
</main>'''
    return _shell(
        title="Content Directory | Jake Troubleshoots",
        description="Browse static HTML directories for every published Jake Troubleshoots guide, preventive maintenance procedure, and Biomed Basics article.",
        canonical_path=MASTER_PATH,
        prefix="",
        main=main,
    )


def _pagination(pillar: Pillar, page_number: int, page_count: int) -> str:
    links = [f'<a href="../{MASTER_PATH}#{pillar.key}">Directory home</a>']
    if page_number > 1:
        links.append(f'<a href="{pillar.page_prefix}-{page_number - 1:03d}.html" rel="prev">Previous</a>')
    for number in range(1, page_count + 1):
        current = ' aria-current="page"' if number == page_number else ""
        links.append(
            f'<a href="{pillar.page_prefix}-{number:03d}.html"{current}>'
            f'Page {number}</a>'
        )
    if page_number < page_count:
        links.append(f'<a href="{pillar.page_prefix}-{page_number + 1:03d}.html" rel="next">Next</a>')
    return '<nav class="browse-buttons" aria-label="Directory pages">' + "\n        ".join(links) + "</nav>"


def _listing_page(
    pillar: Pillar,
    entries: list[tuple[str, str]],
    page_number: int,
    page_count: int,
    page_size: int,
) -> str:
    start = (page_number - 1) * page_size
    page_entries = entries[start:start + page_size]
    listing = "\n".join(
        f'        <li><a href="../{html.escape(url, quote=True)}">{html.escape(title)}</a></li>'
        for title, url in page_entries
    )
    page_title = f"{pillar.name} Directory – Page {page_number} of {page_count} | Jake Troubleshoots"
    description = (
        f"Browse published {pillar.name.lower()}, page {page_number} of {page_count}, "
        "with direct static HTML links to each resource."
    )
    navigation = _pagination(pillar, page_number, page_count)
    main = f'''<section class="hero">
  <h1 id="page-heading" tabindex="-1">{html.escape(pillar.name)} Directory – Page {page_number} of {page_count}</h1>
  <p>Page {page_number} of {page_count}. Direct links to published {html.escape(pillar.name.lower())}.</p>
</section>
<main>
  <section class="content-box">
    <h2>{html.escape(pillar.name)}: {start + 1}&ndash;{start + len(page_entries)}</h2>
    <ul>
{listing}
    </ul>
    {navigation}
  </section>
</main>'''
    return _shell(
        title=page_title,
        description=description,
        canonical_path=_page_path(pillar, page_number),
        prefix="../",
        main=main,
    )


def build_outputs(root: Path = ROOT, page_size: int = PAGE_SIZE) -> dict[str, str]:
    """Return all expected generated paths and deterministic UTF-8 text."""
    if page_size < 1:
        raise DirectoryBuildError("Page size must be at least 1")
    content = load_content(root)
    outputs = {MASTER_PATH: _master_page(content, page_size)}
    for pillar, entries in content.items():
        page_count = (len(entries) + page_size - 1) // page_size
        for page_number in range(1, page_count + 1):
            outputs[_page_path(pillar, page_number)] = _listing_page(
                pillar, entries, page_number, page_count, page_size
            )
    return outputs


def _generated_files(root: Path) -> set[str]:
    directory = root / DIRECTORY_NAME
    if not directory.exists():
        return set()
    found: set[str] = set()
    for path in directory.glob("*.html"):
        relative = path.relative_to(root).as_posix()
        text = path.read_text(encoding="utf-8")
        if GENERATED_MARKER not in text:
            raise DirectoryBuildError(
                f"Refusing to manage unmarked HTML file in generated directory: {relative}"
            )
        found.add(relative)
    return found


def changed_outputs(root: Path, outputs: dict[str, str]) -> tuple[list[str], list[str]]:
    """Return changed/missing expected paths and stale generated paths."""
    changed = []
    for relative, expected in outputs.items():
        path = root / relative
        if not path.is_file() or path.read_text(encoding="utf-8") != expected:
            changed.append(relative)
    stale = sorted(_generated_files(root) - set(outputs))
    return sorted(changed), stale


def write_outputs(root: Path, outputs: dict[str, str]) -> tuple[list[str], list[str]]:
    """Atomically write changed pages, then remove obsolete generated pages."""
    changed, stale = changed_outputs(root, outputs)
    for relative in changed:
        target = root / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        with tempfile.NamedTemporaryFile(
            mode="w", encoding="utf-8", newline="\n", dir=target.parent, delete=False
        ) as temporary:
            temporary.write(outputs[relative])
            temporary_path = Path(temporary.name)
        os.replace(temporary_path, target)
    for relative in stale:
        (root / relative).unlink()
    return changed, stale


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--page-size", type=int, default=PAGE_SIZE)
    parser.add_argument("--check", action="store_true", help="Validate and report drift without writing")
    args = parser.parse_args(argv)
    root = args.root.resolve()
    try:
        outputs = build_outputs(root, args.page_size)
        changed, stale = changed_outputs(root, outputs)
        if args.check:
            if changed or stale:
                print(f"Content directory is out of date: {len(changed)} changed/missing, {len(stale)} stale.")
                return 1
        else:
            changed, stale = write_outputs(root, outputs)
        content = load_content(root)
    except (DirectoryBuildError, OSError) as error:
        print(f"Content directory build failed: {error}")
        return 2
    total_links = sum(len(entries) for entries in content.values())
    action = "checked" if args.check else "generated"
    print(
        f"Content directory {action}: {total_links} destinations, {len(outputs) - 1} listing pages, "
        f"{len(changed)} changed/missing, {len(stale)} stale."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
